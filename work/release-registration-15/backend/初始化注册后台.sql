        (source_type IN ('文件导入','图片导入','导入更新') OR effective_date<=p_today) DESC,effective_date DESC,id DESC)
    )
    SELECT coalesce(jsonb_agg(to_jsonb(r)-'rn' ORDER BY customer,grade,color,tax_type),'[]'::jsonb)
    FROM ranked r WHERE rn=1
  );
END $$;

